fruit = ["banana", "apple", "lichi", "chickoo"]

fruit.sort() # Alphabettical Sorting in String 

print(fruit)

# List - Reverse - Sort

list.sort(reverse = True)

print(list)

fruit.sort(reverse = True) # Alphabetical Reverse Sorting for String

print(fruit)

