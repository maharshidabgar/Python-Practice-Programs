# using for & range

# 1. Print numbers form 1 to 100.

for i in range(1, 101, 1):

    print(i)

# 2. Print numbers from 100 to 1.

for r in range(100, 0, -1):

    print(r)

# 3. Print the Multiplication table of a number n.

n = int(input("Enter a Number : "))

for m in range(1, 11):

    print(n * m)